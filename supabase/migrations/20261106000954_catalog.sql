-- Catalog: anime data from cedya77/anime-offline-database (ODbL 1.0 + DbCL 1.0).
-- ODbL data only. User data never lives in this schema.
-- Written by the importer (src/sync) over a direct Postgres connection; read-only for everyone else.

create extension if not exists pg_trgm with schema extensions;

create schema catalog;

-- ---------------------------------------------------------------------------
-- Types
-- ---------------------------------------------------------------------------

create type catalog.anime_type as enum ('tv', 'movie', 'ova', 'ona', 'special');
create type catalog.anime_status as enum ('finished', 'ongoing', 'upcoming');
create type catalog.season as enum ('winter', 'spring', 'summer', 'fall');
create type catalog.title_kind as enum ('main', 'synonym');
create type catalog.studio_role as enum ('studio', 'producer');
create type catalog.alias_source as enum ('import', 'override');
create type catalog.run_status as enum ('running', 'succeeded', 'failed');
create type catalog.run_trigger as enum ('schedule', 'push', 'manual');

-- ---------------------------------------------------------------------------
-- Provenance
-- ---------------------------------------------------------------------------

create table catalog.data_sources (
  id bigint generated always as identity primary key,
  slug text not null unique,
  name text not null,
  url text not null,
  licence text not null,
  attribution text not null,
  data_type text not null,
  is_active boolean not null default false,
  priority integer not null default 100,
  created_at timestamptz not null default now()
);

-- One active source per data type. Extra sources only fill gaps.
create unique index data_sources_one_active_per_type
  on catalog.data_sources (data_type)
  where is_active;

create table catalog.import_runs (
  id bigint generated always as identity primary key,
  data_source_id bigint not null references catalog.data_sources (id),
  release_tag text not null,
  sha256 text not null,
  trigger catalog.run_trigger not null,
  git_commit text,
  status catalog.run_status not null default 'running',
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  entry_count integer,
  inserted integer,
  updated integer,
  unchanged integer,
  retired integer,
  revived integer,
  merged integer,
  split integer,
  unresolved_relations integer,
  details jsonb,
  error text
);

create index import_runs_status_started_idx
  on catalog.import_runs (status, started_at desc);

-- ---------------------------------------------------------------------------
-- Anime
-- ---------------------------------------------------------------------------

create table catalog.anime (
  id bigint generated by default as identity primary key,
  title text not null,
  type catalog.anime_type,
  episodes integer check (episodes > 0),
  status catalog.anime_status,
  season catalog.season,
  year smallint check (year >= 1900),
  duration_seconds integer check (duration_seconds > 0),
  content_hash text not null,
  first_seen_run_id bigint not null references catalog.import_runs (id),
  -- The run that last inserted, changed, revived or retired this row.
  last_changed_run_id bigint not null references catalog.import_runs (id),
  -- Never deleted: an anime that leaves the dataset is retired.
  retired_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index anime_active_idx on catalog.anime (id) where retired_at is null;
create index anime_first_seen_run_idx on catalog.anime (first_seen_run_id);
create index anime_last_changed_run_idx on catalog.anime (last_changed_run_id);

create table catalog.external_ids (
  site text not null,
  external_id text not null,
  anime_id bigint not null references catalog.anime (id),
  url text not null,
  primary key (site, external_id)
);

create index external_ids_anime_idx on catalog.external_ids (anime_id);

create table catalog.anime_titles (
  id bigint generated always as identity primary key,
  anime_id bigint not null references catalog.anime (id),
  title text not null,
  kind catalog.title_kind not null,
  -- Filled later; the dataset does not label title languages.
  lang text,
  -- NFKC, lowercase, single spaces. Set by the importer.
  search_text text not null,
  unique (anime_id, search_text)
);

-- Search with `search_text %> $query` (word similarity), the form the index serves.
-- fastupdate off: rows go straight into the index instead of a pending list, which
-- otherwise makes the planner skip the index after a bulk load until vacuum runs.
create index anime_titles_search_trgm_idx
  on catalog.anime_titles using gin (search_text extensions.gin_trgm_ops)
  with (fastupdate = off);

create table catalog.studios (
  id bigint generated always as identity primary key,
  key text not null unique,
  name text not null
);

create table catalog.studio_aliases (
  raw_name text primary key,
  studio_id bigint not null references catalog.studios (id),
  source catalog.alias_source not null default 'import'
);

create index studio_aliases_studio_idx on catalog.studio_aliases (studio_id);

create table catalog.anime_studios (
  anime_id bigint not null references catalog.anime (id),
  studio_id bigint not null references catalog.studios (id),
  role catalog.studio_role not null,
  primary key (anime_id, studio_id, role)
);

create index anime_studios_studio_idx on catalog.anime_studios (studio_id);

create table catalog.tags (
  id bigint generated always as identity primary key,
  name text not null unique
);

create table catalog.anime_tags (
  anime_id bigint not null references catalog.anime (id),
  tag_id bigint not null references catalog.tags (id),
  primary key (anime_id, tag_id)
);

create index anime_tags_tag_idx on catalog.anime_tags (tag_id);

-- Directed and untyped, as published (no sequel/prequel in the dataset).
create table catalog.anime_relations (
  anime_id bigint not null references catalog.anime (id),
  related_anime_id bigint not null references catalog.anime (id),
  primary key (anime_id, related_anime_id),
  check (anime_id <> related_anime_id)
);

create index anime_relations_related_idx on catalog.anime_relations (related_anime_id);

create table catalog.anime_redirects (
  from_anime_id bigint primary key references catalog.anime (id),
  to_anime_id bigint not null references catalog.anime (id),
  reason text not null check (reason in ('merged')),
  created_run_id bigint not null references catalog.import_runs (id),
  created_at timestamptz not null default now(),
  check (from_anime_id <> to_anime_id)
);

create index anime_redirects_to_idx on catalog.anime_redirects (to_anime_id);

-- Community corrections. The importer never writes, updates or deletes these.
create table catalog.overrides (
  id bigint generated always as identity primary key,
  anime_id bigint not null references catalog.anime (id),
  field text not null check (
    field in ('title', 'type', 'episodes', 'status', 'season', 'year', 'duration_seconds')
  ),
  value jsonb not null,
  reason text not null,
  created_by text not null,
  created_at timestamptz not null default now(),
  unique (anime_id, field)
);

-- ---------------------------------------------------------------------------
-- Service-only data
-- ---------------------------------------------------------------------------

-- Orders the swipe deck internally. Never shown to users, so never readable by them.
create table catalog.anime_scores (
  anime_id bigint primary key references catalog.anime (id),
  arithmetic_geometric_mean double precision not null,
  arithmetic_mean double precision not null,
  median double precision not null
);

-- The entry as published, for provenance and later decisions (e.g. artwork).
create table catalog.anime_source_records (
  anime_id bigint primary key references catalog.anime (id),
  payload jsonb not null,
  content_hash text not null
);

-- Staging: truncated at the start and end of every run.
create unlogged table catalog.staging_anime (
  anime_id bigint primary key,
  title text not null,
  type catalog.anime_type,
  episodes integer,
  status catalog.anime_status,
  season catalog.season,
  year smallint,
  duration_seconds integer,
  content_hash text not null,
  payload jsonb not null,
  score_agm double precision,
  score_mean double precision,
  score_median double precision
);

create unlogged table catalog.staging_external_ids (
  anime_id bigint not null,
  site text not null,
  external_id text not null,
  url text not null
);

create unlogged table catalog.staging_titles (
  anime_id bigint not null,
  title text not null,
  kind catalog.title_kind not null,
  search_text text not null
);

create unlogged table catalog.staging_studios (
  key text primary key,
  name text not null
);

create unlogged table catalog.staging_studio_aliases (
  raw_name text primary key,
  key text not null
);

create unlogged table catalog.staging_anime_studios (
  anime_id bigint not null,
  raw_name text not null,
  role catalog.studio_role not null
);

create unlogged table catalog.staging_anime_tags (
  anime_id bigint not null,
  tag text not null
);

create unlogged table catalog.staging_relations (
  anime_id bigint not null,
  site text not null,
  external_id text not null
);

create unlogged table catalog.staging_merges (
  from_anime_id bigint primary key,
  to_anime_id bigint not null
);

create unlogged table catalog.staging_retired (
  anime_id bigint primary key
);

